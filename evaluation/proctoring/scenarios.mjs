// Scripted behaviours performed once, mid-quiz, on the real React client.
// Each returns notes about what actually happened in the browser (e.g. whether Esc really left fullscreen).
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const isFullscreen = (page) => page.evaluate(() => Boolean(document.fullscreenElement));

// Click somewhere neutral on the quiz page (the question card), never on browser chrome
const clickInsidePage = async (page) => {
  const target = page.locator(".question-section").first();
  if (await target.count()) await target.click({ position: { x: 20, y: 20 } });
  else await page.mouse.click(400, 300);
};

const answerFirstOption = async (page) => {
  // MCQ options are labels; true/false questions use buttons
  const option = page.locator("label.option, .true-false-container button").first();
  if (await option.count()) await option.click().catch(() => {});
};

